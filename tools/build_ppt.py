def gs(slide, name):
    return slide.Shapes.Item(name)

def try_set(slide, name, text):
    try:
        gs(slide, name).TextFrame.TextRange.Text = text
    except Exception as e:
        log(f"[WARN] try_set failed {name}: {e}")

def set_para(slide, name, para_1b, text):
    try:
        gs(slide, name).TextFrame.TextRange.Paragraphs(para_1b, 1).Text = text
    except Exception as e:
        log(f"[WARN] set_para failed {name} p{para_1b}: {e}")

def set_run(slide, name, para_1b, run_1b, text):
    try:
        p = gs(slide, name).TextFrame.TextRange.Paragraphs(para_1b, 1)
        p.Runs(run_1b, 1).Text = text
    except Exception as e:
        log(f"[WARN] set_run failed {name} p{para_1b}r{run_1b}: {e}")

def set_marker_para(slide, name, para_1b, marker_len, content):
    try:
        p = gs(slide, name).TextFrame.TextRange.Paragraphs(para_1b, 1)
        total = len(p.Text)
        rng = p.Characters(marker_len + 1, max(total - marker_len, 1))
        rng.Text = content
    except Exception as e:
        log(f"[WARN] set_marker_para failed {name} p{para_1b}: {e}")

FRAME_PAD = 41148 / 12700.0  # EMU -> points (COM shape geometry is in points)

def fit_box(l, t, w, h, mw, mh):
    box_r = w / h
    m_r = mw / mh
    if m_r > box_r:
        nw = w; nh = w / m_r
    else:
        nh = h; nw = h * m_r
    return l + (w - nw) / 2, t + (h - nh) / 2, nw, nh

def replace_with_video(slide, pic_name, media_path, mw, mh, frame_name=None, pad=None, delete_names=None):
    shp = gs(slide, pic_name)
    l, t, w, h = shp.Left, shp.Top, shp.Width, shp.Height
    shp.Delete()
    if delete_names:
        for dn in delete_names:
            try:
                gs(slide, dn).Delete()
            except Exception as e:
                log(f"[WARN] delete {dn} failed: {e}")
    nl, nt, nw, nh = fit_box(l, t, w, h, mw, mh)
    new_shp = slide.Shapes.AddMediaObject2(media_path, LinkToFile=False, SaveWithDocument=True,
                                            Left=nl, Top=nt, Width=nw, Height=nh)
    try:
        new_shp.AnimationSettings.PlaySettings.LoopUntilStopped = True
        new_shp.AnimationSettings.PlaySettings.PlayOnEntry = True
        new_shp.AnimationSettings.PlaySettings.HideWhileNotPlaying = False
        new_shp.AnimationSettings.PlaySettings.StopAfterSlides = 0
    except Exception as e:
        log(f"[WARN] legacy playsettings failed on {pic_name}: {e}")
    try:
        seq = slide.TimeLine.MainSequence
        eff = seq.AddEffect(new_shp, 76, 0, 1)
        eff.Timing.RepeatCount = 999999
    except Exception as e:
        log(f"[WARN] timeline effect failed on {pic_name}: {e}")
    if frame_name and pad is not None:
        try:
            frame = gs(slide, frame_name)
            frame.Left = nl - pad; frame.Top = nt - pad
            frame.Width = nw + 2 * pad; frame.Height = nh + 2 * pad
        except Exception as e:
            log(f"[WARN] frame resize failed {frame_name}: {e}")
    return new_shp

def replace_with_picture(slide, pic_name, media_path, mw, mh, frame_name=None, pad=None):
    shp = gs(slide, pic_name)
    l, t, w, h = shp.Left, shp.Top, shp.Width, shp.Height
    shp.Delete()
    nl, nt, nw, nh = fit_box(l, t, w, h, mw, mh)
    new_shp = slide.Shapes.AddPicture(media_path, False, True, nl, nt, nw, nh)
    if frame_name and pad is not None:
        try:
            frame = gs(slide, frame_name)
            frame.Left = nl - pad; frame.Top = nt - pad
            frame.Width = nw + 2 * pad; frame.Height = nh + 2 * pad
        except Exception as e:
            log(f"[WARN] frame resize failed {frame_name}: {e}")
    return new_shp

def rgb(hexstr):
    r, g, b = int(hexstr[0:2], 16), int(hexstr[2:4], 16), int(hexstr[4:6], 16)
    return r + g * 256 + b * 65536

def fix_bg(slide, name="Rectangle 1"):
    try:
        shp = gs(slide, name)
        shp.Fill.Solid()
        shp.Fill.ForeColor.RGB = rgb("0A0A14")
    except Exception as e:
        log(f"[WARN] fix_bg failed: {e}")

