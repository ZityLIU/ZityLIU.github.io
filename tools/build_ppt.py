def footer_page(slide, name, num):
    try:
        p = gs(slide, name).TextFrame.TextRange.Paragraphs(1, 1)
        if p.Runs().Count >= 2:
            p.Runs(1, 1).Text = f"{num:02d}"
            p.Runs(2, 1).Text = " / 22"
        else:
            p.Text = f"{num:02d} / 22"
    except Exception as e:
        log(f"[WARN] footer_page failed {name}: {e}")

